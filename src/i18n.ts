export type Lang = "fr" | "en";
const dicts: Record<Lang, Record<TKey, string>> = { fr, en };

export type T = (key: TKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = dicts[lang] ?? fr;
  return (key, vars) => {
    let s: string = d[key] ?? fr[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** Translates backend errors of the form `ERR:<code>[:<arg>]`; other messages are returned unchanged. */
export function translateError(t: T, message: string): string {
  const m = /^ERR:([a-z_]+)(?::(.*))?$/.exec(message);
  if (!m) return message;
  const key = `err.${m[1]}` as TKey;
  const text = t(key, { arg: m[2] ?? "" });
  return text === key ? message : text;
}
